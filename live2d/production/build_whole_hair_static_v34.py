"""Package current left-view static hair into an assembled, editable material PSD.
Uses tiled psd-tools composition to keep memory below desktop VM limits.
No Cubism mesh/angle keyforms/physics are generated by this script.
"""
import json,hashlib,gc,argparse
from pathlib import Path
import numpy as np
from PIL import Image,ImageDraw,ImageFont
from scipy.ndimage import binary_fill_holes,label
from psd_tools import PSDImage
from psd_tools.api.layers import Group
from finish_hair_static_v34 import SOURCE,OUT,W,H,DX,ORDER,ROOTS,prepare
from split_left_head_parts_v34 import pixels,clone,add,sha
from complete_fringe_materials_v34 import checker,FONT
PSD=OUT/'Rurino_Whole_Hair_Static_v034.psd'
HAIR=['Large_L','Large_R','Small_L','Small_R','Thin_R','Temple_R','Cheek_L','Cheek_R','Crown']
FG=['Left_Cheek_EyeOverlap_SOURCE','Left_Fringe_EyeOverlap_SOURCE','RightFringe_ForegroundTips_SOURCE']
BROWS=['Eyebrow_L_Full_LOCAL_CLEANUP','Eyebrow_R_Full_LOCAL_CLEANUP']

def tile_render(psd):
 im=Image.new('RGBA',(W,H))
 for y in range(0,H,704):
  for x in range(0,W,864):
   box=(x,y,min(x+864,W),min(y+704,H));tile=psd.composite(viewport=box,force=True,color=(0,0,0),alpha=0);im.paste(tile,(x,y))
 return im

def visible_state(psd,state):
 for g in psd:
  if g.name.startswith('02_'):g.visible=g.name=='02_'+state

def build():
 src=PSDImage.open(SOURCE);original={l.name:l for l in pixels(src)}
 psd=PSDImage.new('RGBA',(W,H),color=0);layerfiles={}
 def load_add(parent,n):
  im=Image.open(OUT/'layers'/(n+'.png')).convert('RGBA');l=add(psd,parent,im,n);layerfiles[n]=OUT/'layers'/(n+'.png');return l
 # All latest materials enabled once. Historical candidates remain in the
 # unchanged input PSD in the delivery, never superimposed in the active PSD.
 groups=[('01a_Back_Hair',['Large_L','Large_R','Small_L','Small_R']),('01b_Body_Neck',['Body_Visible','Neck_Visible']),('01c_FrontThin',['Thin_R']),('01d_Face_Ear',['Fringe_R_Context_AfterTipRecovery_SOURCE','Left_FringeCheek_SkinContext_SOURCE','Face_Boundary_Underlap_SOURCE','FacePaint_AfterCheekRecovery_SOURCE','Ear_Near_ImageRight']),('01e_HeadHair',['Temple_R','Cheek_L','Cheek_R','Crown']),('01f_Flowers',['Flower_ImageLeft','Flower_ImageRight'])]
 for name,names in groups:
  g=Group.new(name,parent=psd)
  for n in names:load_add(g,n)
 for state in ['Open','Half','Closed']:
  sg=next(g for g in src if g.name=='02_'+state);clone([sg],psd,psd,[]);g=psd[-1];g.visible=state=='Open'
  for l in pixels(g):l.left+=DX;layerfiles[l.name]=OUT/'layers'/(l.name+'.png')
 g=Group.new('03_Hair_Over_Eyes_Preserved',parent=psd)
 for n in FG:load_add(g,n)
 g=Group.new('04_Independent_Brows_Preserved',parent=psd)
 for n in BROWS:load_add(g,n)
 print('Built',len(list(pixels(psd))),'layers',flush=True)
 # Write a genuine tiled merge preview, not an empty PSD preview.
 default=tile_render(psd);default.save(OUT/'qa/assembled-Open.png');print('Rendered Open',flush=True)
 psd._update_record();psd._record.image_data.set_data([ch.tobytes() for ch in default.split()],psd._record.header)
 with PSD.open('wb') as f:psd._record.write(f)
 del psd;gc.collect()
 saved=PSDImage.open(PSD);layers={l.name:l for l in pixels(saved)};checks=[]
 for name,l in layers.items():
  png=Image.open(layerfiles[name]).convert('RGBA');box=png.getbbox()
  assert tuple(l.bbox)==tuple(box),(name,l.bbox,box)
  assert np.array_equal(np.array(l.topil().convert('RGBA')),np.array(png.crop(box))),name
  checks.append({'name':name,'bbox':list(l.bbox),'png_sha256':sha(layerfiles[name]),'roundtrip_exact':True,'clipping':bool(l.clipping_layer)})
 # Protect all face/eye/brow/ear/body pixels and original eye clipping behavior.
 protected=[n for n in layers if n in original and not n.startswith('Flower')]
 for n in protected:
  old,new=original[n],layers[n]
  assert new.left==old.left+DX and new.top==old.top,n
  assert np.array_equal(np.array(old.topil().convert('RGBA')),np.array(new.topil().convert('RGBA'))),n
  assert (old.opacity,old.blend_mode,old.visible,old.clipping_layer)==(new.opacity,new.blend_mode,new.visible,new.clipping_layer),n
 print('Verified pixel layers and',len(protected),'protected originals',flush=True)
 # Compare the actual saved PSD rendering against its embedded preview.
 rendered=tile_render(saved);assert np.array_equal(np.array(rendered),np.array(default))
 states=[]
 for state in ['Open','Half','Closed']:
  visible_state(saved,state)
  im=default if state=='Open' else tile_render(saved);im.save(OUT/'qa'/('assembled-'+state+'.png'))
  states.append({'state':state,'file':'qa/assembled-'+state+'.png','sha256':sha(OUT/'qa'/('assembled-'+state+'.png')),'original_iris_clipping_preserved':True})
  print('Verified',state,flush=True)
 hair=[]
 for n in HAIR:
  a=np.array(Image.open(OUT/'layers'/(n+'.png')));m=a[:,:,3]>127;box=Image.fromarray(a).getbbox();_,count=label(m,np.ones((3,3)))
  edge=int(m[0].sum()+m[-1].sum()+m[:,0].sum()+m[:,-1].sum());assert edge==0,n
  holes=int((binary_fill_holes(m)&~m).sum());assert count==1 and holes==0,(n,count,holes)
  hair.append({'name':n,'bbox':list(box),'opaque_components':count,'enclosed_hole_pixels':holes,'canvas_edge_pixels':edge})
 report={'stage':'whole-hair-static-assembly','input_psd':str(SOURCE),'input_psd_sha256':sha(SOURCE),'saved_psd':PSD.name,'saved_psd_sha256':sha(PSD),'canvas':[W,H],'original_coordinate_translation':[DX,0],'pixel_layers':len(layers),'all_png_layers_roundtrip_exact':True,'protected_original_layers':protected,'protected_rgba_offsets_blend_opacity_clipping_exact':True,'saved_default_composite_exact':True,'default_eye_state':'Open','states':states,'hair_alpha_audit':hair,'layer_checks':checks,'scope':'left-view static material assembly and concealed surface cleanup; inferred extensions','original_134_layer_psd_preserved_separately':True,'libtv_generation_used':False,'limitations':['concealed roots and off-canvas tips locally inferred; not recovered unseen original artwork','body remains original waist-cropped bust','static eye states only, no continuous motion validation','no new Cubism meshes, turn/up-down keyforms, body sway, hair physics or runtime model']}
 (OUT/'verification.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
 previews();print(json.dumps({'psd':str(PSD),'layers':len(layers),'protected':len(protected),'hair_alpha':hair},ensure_ascii=False,indent=2))

